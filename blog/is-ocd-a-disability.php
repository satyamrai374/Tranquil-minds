                    <!-- Section 5: ADA Protections -->
                    <h2 id="ada-protections" class="text-3xl text-primary mt-12 mb-5" style="font-family: 'Bauhaus Soft', cursive;">Is OCD Protected Under the Americans with Disabilities Act (ADA)?</h2>
                    <p>
                        <strong>Yes. Under Title I of the ADA and the ADA Amendments Act (ADAAA), OCD qualifies as a recognized psychiatric disability.</strong>
                    </p>
                    <p>
                        The ADA defines disability as an impairment that substantially limits one or more major life activities. The EEOC explicitly identifies these to include thinking, concentrating, learning, sleeping, neurological function, and working. Because severe intrusive thoughts impair sustained attention and rituals derail schedules, OCD qualifies under federal law, regardless of positive responses to medications.
                    </p>

