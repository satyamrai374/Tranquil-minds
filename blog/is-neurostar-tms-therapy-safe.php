                    <!-- Section 4: Common Side Effects -->
                    <h2 id="common-side-effects" class="text-3xl text-primary mt-12 mb-5" style="font-family: 'Bauhaus Soft', cursive;">Common, Mild Side Effects of NeuroStar TMS &amp; How They Are Managed</h2>
                    <p>
                        While NeuroStar TMS avoids systemic side effects, it is an active therapeutic intervention that engages localized nerve endings in the scalp. Side effects are overwhelmingly mild to moderate, temporary, and diminish significantly over the first 1 to 2 weeks of treatment as habituation occurs.
                    </p>

                    <p>
                        For an expanded breakdown of side effect management protocols, read our detailed guide on <a href="tms-therapy-side-effects.php" class="text-accent underline hover:text-accent-light">Common Side Effects of TMS Therapy</a>.
                    </p>

                    <h3 class="text-2xl text-primary mt-8 mb-4 font-semibold">1. Scalp Discomfort or Mild Pain During Session</h3>
                    <p>
                        The most frequently reported side effect is a localized tapping or mild scalp discomfort underneath the magnetic coil. Because superficial nerve endings reside in the scalp tissue, the magnetic pulses excite these nerve fibers simultaneously with underlying cortical neurons.
                    </p>
                    <ul class="list-disc ml-6 space-y-2 mb-4">
                        <li><strong>Incidence:</strong> Reported by approximately 30%–40% of patients during initial sessions.</li>
                        <li><strong>Duration:</strong> Typically resolves within minutes after each session ends and disappears entirely after 5–7 treatment sessions.</li>
                        <li><strong>Management:</strong> Our trained clinical technicians adjust motor threshold energy parameters, fine-tune coil positioning, and recommend over-the-counter pain relievers (such as acetaminophen or ibuprofen) prior to early sessions if needed.</li>
                    </ul>

                    <h3 class="text-2xl text-primary mt-8 mb-4 font-semibold">2. Mild Post-Treatment Tension Headaches</h3>
                    <p>
                        Some patients experience a mild, transient headache following their appointment, similar in feel to a mild tension headache.
                    </p>
                    <ul class="list-disc ml-6 space-y-2 mb-4">
                        <li><strong>Incidence:</strong> Occurs in roughly 25% of patients during the first week.</li>
                        <li><strong>Duration:</strong> Resolves quickly within 1 to 2 hours post-session.</li>
                        <li><strong>Management:</strong> Easily managed with standard over-the-counter analgesics, proper hydration, and adequate rest.</li>
                    </ul>

                    <h3 class="text-2xl text-primary mt-8 mb-4 font-semibold">3. Facial Muscle Twitching or Tingling</h3>
                    <p>
                        During the active magnetic pulse sequence, patients may observe temporary, involuntary twitching of facial or eyebrow muscles on the left side of the face.
                    </p>
                    <ul class="list-disc ml-6 space-y-2 mb-4">
                        <li><strong>Nature:</strong> Harmless physiological response caused by facial nerve branch proximity.</li>
                        <li><strong>Management:</strong> Stops instantly the moment the pulse train pauses. Re-positioning the treatment coil by just a few millimeters eliminates discomfort while preserving therapeutic effectiveness.</li>
                    </ul>

