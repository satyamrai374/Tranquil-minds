                    <h3 class="text-2xl text-primary mt-8 mb-4 font-semibold">Safety Contraindications: Non-Removable Metal Near the Head</h3>
                    <p>
                        Because NeuroStar uses strong magnetic pulses, the primary safety contraindication involves magnetic-sensitive or conductive metal objects in or near the head and neck.
                    </p>
                    <div class="p-6 bg-amber-50 border border-amber-200 rounded-2xl my-6 not-prose">
                        <h4 class="text-lg font-bold text-amber-900 mb-2">Non-Candidates for TMS Therapy:</h4>
                        <p class="text-sm text-amber-800 leading-relaxed mb-3">
                            You cannot receive TMS therapy if you have non-removable, ferromagnetically sensitive metal implanted within 30 centimeters (12 inches) of the head coil, including:
                        </p>
                        <ul class="list-disc ml-5 text-sm text-amber-800 space-y-1">
                            <li>Cochlear implants or metallic hearing devices</li>
                            <li>Aneurysm clips or coils in the brain</li>
                            <li>Deep brain stimulators (DBS) or vagus nerve stimulators</li>
                            <li>Metallic shrapnel, bullet fragments, or metallic eye implants</li>
                            <li>Stents or implanted devices in the head, neck, or carotid arteries</li>
                        </ul>
                    </div>

