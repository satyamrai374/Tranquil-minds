                    <h2 id="therapy-cost-with-insurance" class="text-3xl text-primary mt-12 mb-5" style="font-family: 'Bauhaus Soft', cursive;">How Much Does Therapy Cost With Insurance?</h2>
                    <p>
                        <strong>With insurance, most patients pay a copay, a coinsurance percentage, or the plan's negotiated rate until their deductible is met.</strong> Your actual cost depends on four terms in your plan:
                    </p>
                    <ol class="list-decimal pl-5 mb-6 space-y-2">
