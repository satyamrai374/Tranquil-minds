                    <!-- Section 1: What Is OCD? -->
                    <h2 id="what-is-ocd" class="text-3xl text-primary mt-12 mb-5" style="font-family: 'Bauhaus Soft', cursive;">What Is OCD?</h2>
                    <p>
                        <strong>Obsessive-Compulsive Disorder (OCD)</strong> is a chronic, neurobiological mental health condition recognized by the American Psychiatric Association in the <em>DSM-5-TR</em>. It is defined by a repetitive, involuntary cycle of obsessions and compulsions:
                    </p>
                    <ul class="list-disc pl-5 mb-6 space-y-2">
                        <li><strong>Obsessions:</strong> Repeated, persistent, and unwanted thoughts, urges, or intrusive mental images that trigger intense anxiety, disgust, or dread. These thoughts feel alien and contrary to the person's values (ego-dystonic).</li>
                        <li><strong>Compulsions:</strong> Repetitive behaviors or mental rituals that a person feels driven to perform in response to an obsession, designed to reduce distress or prevent a dreaded catastrophe.</li>
                    </ul>
                    <p>
                        Clinical neuroscience shows that OCD is driven by neurochemical dysregulation within the <strong>cortico-striato-thalamo-cortical (CSTC) circuit</strong>—the communication pathway connecting the prefrontal cortex with deeper brain structures responsible for habit regulation and error detection. OCD is a recognized medical disorder, not a lack of willpower or personal quirk. Learn more about clinical presentations on <a href="https://en.wikipedia.org/wiki/Obsessive%E2%80%93compulsive_disorder" target="_blank" rel="noopener noreferrer" class="text-accent underline hover:text-accent-light">Wikipedia's OCD Overview</a>.
                    </p>

                    <!-- Section 2: Common Symptoms & Daily Life Impact -->
                    <h2 id="symptoms-daily-life" class="text-3xl text-primary mt-12 mb-5" style="font-family: 'Bauhaus Soft', cursive;">Common Symptoms &amp; How OCD Affects Daily Life</h2>
                    <p>
                        OCD symptoms manifest across several common thematic subtypes. While popular awareness focuses on cleanliness, the disorder encompasses a wide range of distressing themes:
                    </p>
                    <div class="grid grid-cols-1 md:grid-cols-2 gap-4 my-6 not-prose">
                        <div class="p-5 bg-[#FAFAFF] border border-primary/10 rounded-2xl">
                            <h4 class="font-bold text-primary mb-1">Contamination &amp; Cleaning</h4>
                            <p class="text-sm text-gray-600">Intense dread of germs, chemicals, or bodily fluids, leading to hours of compulsive handwashing, showering, or cleaning rituals.</p>
                        </div>
                        <div class="p-5 bg-[#FAFAFF] border border-primary/10 rounded-2xl">
                            <h4 class="font-bold text-primary mb-1">Checking &amp; Harm Prevention</h4>
                            <p class="text-sm text-gray-600">Fear of causing accidental harm or fires, resulting in repeated checking of door locks, stoves, appliances, or retracing driving routes.</p>
                        </div>
                        <div class="p-5 bg-[#FAFAFF] border border-primary/10 rounded-2xl">
                            <h4 class="font-bold text-primary mb-1">Symmetry, Ordering &amp; "Just Right"</h4>
                            <p class="text-sm text-gray-600">Extreme discomfort until items are aligned perfectly, or rituals repeated an exact number of times until an internal "click" is felt.</p>
                        </div>
                        <div class="p-5 bg-[#FAFAFF] border border-primary/10 rounded-2xl">
                            <h4 class="font-bold text-primary mb-1">Intrusive / Taboo Thoughts</h4>
                            <p class="text-sm text-gray-600">Terrifying, unwanted thoughts regarding violence, morality, or religion, followed by silent mental prayers or reassurance-seeking.</p>
                        </div>
                    </div>

                    <h3 class="text-2xl text-primary mt-8 mb-4 font-semibold">How OCD Affects a Person's Life: Occupational, Social &amp; Emotional Strain</h3>
                    <p>
                        When compulsions take over, they consume massive amounts of mental bandwidth and daily hours:
                    </p>
                    <ul class="list-disc pl-5 mb-6 space-y-2">
