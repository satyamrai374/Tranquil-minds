                    <!-- Section 1: What Is Psychotherapy? -->
                    <h2 id="what-is-psychotherapy" class="text-3xl text-primary mt-12 mb-5" style="font-family: 'Bauhaus Soft', cursive;">What Is Psychotherapy?</h2>
                    <p>
                        <strong>Psychotherapy, often called talk therapy, is a structured, evidence-based treatment in which a licensed mental health professional helps you understand and change the thoughts, emotions, and behaviors that cause distress.</strong> Unlike a casual conversation, therapy follows a clear treatment plan with specific goals, and it uses techniques that research has shown to work. You can read a general overview on <a href="https://en.wikipedia.org/wiki/Psychotherapy" target="_blank" rel="noopener noreferrer" class="text-accent underline hover:text-accent-light">Wikipedia's Psychotherapy page</a>.
                    </p>
                    <p>
                        Psychotherapy is one of the most widely used and well-studied treatments in mental health care. It can be used on its own or alongside <a href="../medication-management.php" class="text-accent underline hover:text-accent-light">medication management</a>, and it helps people of all ages, from teens to older adults.
                    </p>

                    <h3 class="text-2xl text-primary mt-8 mb-4 font-semibold">How Psychotherapy Works</h3>
                    <p>
                        Therapy begins with an intake assessment, where your clinician learns about your symptoms, history, and goals. From there, you meet regularly, usually once a week or every other week for 45 to 60 minutes. Over time, therapy helps you:
                    </p>
                    <ul class="list-disc pl-5 mb-6 space-y-2">
                        <li><strong>Understand your patterns:</strong> Recognize the thoughts and triggers that drive anxiety, low mood, or unhelpful habits.</li>
                        <li><strong>Build practical coping skills:</strong> Learn tools to manage stress, regulate emotions, and solve problems.</li>
                        <li><strong>Process difficult experiences:</strong> Work through grief, trauma, and major life changes in a safe, confidential space.</li>
                        <li><strong>Improve relationships and daily functioning:</strong> Communicate more effectively and feel more confident at work, school, and home.</li>
                    </ul>

                    <h3 class="text-2xl text-primary mt-8 mb-4 font-semibold">Conditions Psychotherapy Commonly Treats</h3>
                    <p>
                        Psychotherapy is a first-line treatment for many conditions, including <a href="../depression.php" class="text-accent underline hover:text-accent-light">depression</a>, <a href="../anxiety.php" class="text-accent underline hover:text-accent-light">anxiety disorders</a>, <a href="../ptsd.php" class="text-accent underline hover:text-accent-light">PTSD</a>, <a href="../ocd.php" class="text-accent underline hover:text-accent-light">OCD</a>, <a href="../bipolar.php" class="text-accent underline hover:text-accent-light">bipolar disorder</a> (alongside medication), <a href="../adhd.php" class="text-accent underline hover:text-accent-light">ADHD</a>, <a href="../postpartum-depression.php" class="text-accent underline hover:text-accent-light">postpartum depression</a>, and <a href="../sleep-disorders.php" class="text-accent underline hover:text-accent-light">sleep problems</a>. Because these are recognized medical diagnoses, therapy to treat them is the kind of care insurance is designed to cover.
                    </p>

                    <h3 class="text-2xl text-primary mt-8 mb-4 font-semibold">Who Provides Psychotherapy?</h3>
                    <p>
                        Insurance pays for therapy delivered by licensed clinicians. These include psychiatrists (MD/DO), psychiatric nurse practitioners (PMHNP), licensed psychologists (PhD/PsyD), licensed independent clinical social workers (LICSW), licensed professional clinical counselors (LPCC), and licensed marriage and family therapists (LMFT). Seeing a licensed, credentialed provider is one of the basic requirements for coverage.
                    </p>

                    <!-- Section 2 -->
                    <h2 id="why-insurance-covers-therapy" class="text-3xl text-primary mt-12 mb-5" style="font-family: 'Bauhaus Soft', cursive;">Why Most Insurance Plans Must Cover Therapy</h2>
                    <p>
                        <strong>Most plans cover psychotherapy because federal law treats mental health care as essential health care.</strong> Two laws do most of the work.
                    </p>

                    <h3 class="text-2xl text-primary mt-8 mb-4 font-semibold">The Mental Health Parity and Addiction Equity Act (MHPAEA)</h3>
                    <p>
                        This law says that if a plan offers mental health benefits, those benefits cannot be more restrictive than its medical and surgical benefits. In practice, a plan generally cannot charge a higher copay for therapy than for a similar specialist visit, or impose tighter visit limits on therapy than on other outpatient care. You can read background on the law in <a href="https://en.wikipedia.org/wiki/Mental_Health_Parity_and_Addiction_Equity_Act" target="_blank" rel="noopener noreferrer" class="text-accent underline hover:text-accent-light">Wikipedia's overview of the Mental Health Parity and Addiction Equity Act</a>.
                    </p>

                    <h3 class="text-2xl text-primary mt-8 mb-4 font-semibold">The Affordable Care Act (ACA)</h3>
                    <p>
                        The ACA lists mental health and substance use disorder services, including behavioral health treatment such as psychotherapy, among the <strong>essential health benefits</strong> that individual and small-group Marketplace plans must include. The official <a href="https://www.healthcare.gov/coverage/mental-health-substance-abuse-coverage/" target="_blank" rel="noopener noreferrer" class="text-accent underline hover:text-accent-light">HealthCare.gov mental health coverage page</a> summarizes these protections.
                    </p>
                    <p>
                        A few plan types, such as short-term health plans, some grandfathered plans, and certain very small employer plans, may follow different rules. That is one reason verifying your specific benefits matters.
                    </p>

                    <!-- Section 2 -->
                    <h2 id="covered-therapy-types" class="text-3xl text-primary mt-12 mb-5" style="font-family: 'Bauhaus Soft', cursive;">What Types of Psychotherapy Does Insurance Usually Cover?</h2>
                    <p>
                        <strong>Insurance typically covers evidence-based outpatient therapy used to treat a diagnosed mental health condition.</strong> Common covered formats include:
                    </p>

                    <div class="grid grid-cols-1 md:grid-cols-2 gap-6 my-8 not-prose">
                        <div class="bg-[#FAFAFF] border border-primary/10 p-6 rounded-2xl shadow-sm">
