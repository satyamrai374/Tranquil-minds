                    <!-- Section 3: How Is OCD Diagnosed? -->
                    <h2 id="how-is-ocd-diagnosed" class="text-3xl text-primary mt-12 mb-5" style="font-family: 'Bauhaus Soft', cursive;">How Is OCD Diagnosed?</h2>
                    <p>
                        A formal OCD diagnosis requires a comprehensive clinical evaluation by a psychiatric provider (such as a board-certified PMHNP or psychiatrist). Under the <strong>DSM-5-TR</strong>, diagnosis requires:
                    </p>
                    <ol class="list-decimal pl-5 mb-6 space-y-2">
                        <li><strong>Presence of obsessions, compulsions, or both.</strong></li>
                        <li><strong>Time Consumption &amp; Impairment:</strong> Symptoms consume over 1 hour daily or cause clinically significant distress in work, academic, or social life.</li>
                        <li><strong>Exclusion of Other Causes:</strong> Symptoms are not caused by substances or a separate medical condition.</li>
                    </ol>
                    <p>
                        Clinicians administer the <strong>Yale-Brown Obsessive Compulsive Scale (Y-BOCS)</strong> to measure symptom severity and treatment progress. At Tranquil Minds, we also utilize objective cognitive evaluations via <a href="../creyos.php" class="text-accent underline hover:text-accent-light">Creyos Health</a> to evaluate focus and cognitive flexibility.
                    </p>

