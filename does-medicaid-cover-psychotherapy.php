                    <h3 class="text-xl sm:text-2xl text-primary mt-6 sm:mt-8 mb-3 sm:mb-4 font-semibold">The Mental Health Parity and Addiction Equity Act (MHPAEA)</h3>
                    <p class="text-gray-600 text-base sm:text-lg leading-relaxed mb-4">
                        The Mental Health Parity and Addiction Equity Act mandates that health insurance plans and Medicaid managed care networks offer behavioral health benefits comparable to medical and surgical coverage. Specifically, insurers cannot impose stricter quantitative treatment limits—such as arbitrary caps on total yearly therapy appointments—or non-quantitative treatment limitations (NQTLs), such as overly demanding prior approval protocols.
                    </p>
                    <p class="text-gray-600 text-base sm:text-lg leading-relaxed mb-4">
                        The Affordable Care Act reinforced these parity protections by defining mental healthcare and substance use disorder services as Essential Health Benefits. You can read clinical background on <a href="https://en.wikipedia.org/wiki/Psychotherapy" target="_blank" rel="noopener noreferrer" class="text-accent underline hover:text-accent-light">Wikipedia's Psychotherapy overview</a> and review federal standards on <a href="https://www.medicaid.gov/medicaid/benefits/behavioral-health-services/index.html" target="_blank" rel="noopener noreferrer" class="text-accent underline hover:text-accent-light">Medicaid.gov's Behavioral Health portal</a>.
                    </p>

                    <h3 class="text-xl sm:text-2xl text-primary mt-6 sm:mt-8 mb-3 sm:mb-4 font-semibold">Managed Care Organizations (MCOs) vs. Fee-for-Service</h3>
                    <p class="text-gray-600 text-base sm:text-lg leading-relaxed mb-4">
                        Most Medicaid recipients receive their healthcare through contracted Managed Care Organizations (MCOs) rather than traditional state-run fee-for-service systems. In Minnesota, health plans such as Blue Plus, UCare, HealthPartners, and Hennepin Health administer Medical Assistance benefits. While every plan must adhere to state and federal parity regulations, each network maintains its own directory of credentialed in-network clinics.
                    </p>

