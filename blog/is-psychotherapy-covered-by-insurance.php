                    <!-- Section 4 -->
                    <h2 id="medical-necessity" class="text-3xl text-primary mt-12 mb-5" style="font-family: 'Bauhaus Soft', cursive;">What "Medical Necessity" Means for Therapy Coverage</h2>
                    <p>
                        <strong>Insurance pays for therapy that treats a diagnosed mental health condition.</strong> This is called medical necessity. Your first appointment, often an intake or diagnostic assessment, helps establish it. Your clinician will review:
                    </p>
                    <ul class="list-disc pl-5 mb-6 space-y-2">
                        <li>Your current symptoms, how long they have lasted, and how severe they feel.</li>
                        <li>How symptoms affect work, school, sleep, relationships, and daily life.</li>
                        <li>Your personal and family mental health history, including past treatment.</li>
                        <li>A treatment plan with clear goals and a recommended session frequency.</li>
                    </ul>
                    <p>
                        A diagnosis, such as major depressive disorder, generalized anxiety disorder, PTSD, ADHD, or an adjustment disorder, becomes part of your health record and is shared with your insurer for billing. Your information remains protected under HIPAA privacy rules.
                    </p>

                    <!-- Section 5 -->
                    <h2 id="in-network-vs-out-of-network" class="text-3xl text-primary mt-12 mb-5" style="font-family: 'Bauhaus Soft', cursive;">In-Network vs. Out-of-Network Therapists</h2>
                    <p>
                        <strong>Seeing an in-network therapist almost always costs less.</strong> In-network providers have agreed rates with your insurer, and the clinic bills your plan directly.
                    </p>
                    <h3 class="text-2xl text-primary mt-8 mb-4 font-semibold">HMO Plans</h3>
                    <p>
                        HMOs usually cover only in-network care. Some may require a referral from your primary care provider before you see a mental health specialist.
                    </p>
                    <h3 class="text-2xl text-primary mt-8 mb-4 font-semibold">PPO and POS Plans</h3>
                    <p>
                        PPOs often include out-of-network benefits. You pay the provider up front, then submit a <strong>superbill</strong> (an itemized receipt with diagnosis and procedure codes) to your insurer for partial reimbursement.
                    </p>

