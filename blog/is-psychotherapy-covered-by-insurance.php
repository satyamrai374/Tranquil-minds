                        <li><strong>Coinsurance:</strong> A percentage of the session cost you pay after your deductible, for example 20%.</li>
                        <li><strong>Out-of-pocket maximum:</strong> The most you pay in a plan year. Once you reach it, covered care is typically paid in full.</li>
