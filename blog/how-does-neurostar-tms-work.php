                    <!-- Section 1: Depression & Brain Biology -->
                    <h2 id="depression-brain-biology" class="text-3xl text-primary mt-12 mb-5" style="font-family: 'Bauhaus Soft', cursive;">Depression and the Underactive Brain: The Neurological Root</h2>
                    <p>
                        Clinical depression is a biological condition involving disruptions in electrical signaling, structural connectivity, and blood flow in specific regions of the brain.
                    </p>
                    <p>
                        Functional neuroimaging studies consistently demonstrate that individuals with depression experience hypometabolism (underactivity) in the <strong>left dorsolateral prefrontal cortex (DLPFC)</strong>. This region oversees critical cognitive and emotional functions:
                    </p>
                    <ul class="list-disc pl-6 mb-6 space-y-2">
                        <li><strong>Mood regulation:</strong> Modulating emotional responses to stress and sadness.</li>
                        <li><strong>Executive functioning:</strong> Mental focus, decision-making, and motivation.</li>
                        <li><strong>Inhibiting negative rumination:</strong> Dampening intrusive feelings of guilt or hopelessness.</li>
                    </ul>
                    <p>
                        When the left DLPFC becomes underactive, communication with deeper emotional centers—such as the amygdala and hippocampus—slows down. Rather than flooding the entire body with synthetic drugs, NeuroStar TMS directly stimulates this dormant region using focused magnetic energy. Learn more on our <a href="../what-is-tms-therapy.php" class="text-accent underline hover:text-accent-light">What Is TMS Therapy page</a>.
                    </p>

