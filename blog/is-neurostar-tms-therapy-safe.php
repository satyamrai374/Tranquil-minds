                    <h2 id="rare-risks" class="text-3xl text-primary mt-12 mb-5" style="font-family: 'Bauhaus Soft', cursive;">Addressing Rare Risks &amp; Misconceptions: Seizures, Memory &amp; ECT</h2>

                    <h3 class="text-2xl text-primary mt-8 mb-4 font-semibold">The Seizure Risk Factor (< 0.1%)</h3>
                    <p>
                        The most serious potential risk associated with magnetic brain stimulation is the accidental induction of a seizure. However, extensive safety data indicates that the risk of a seizure during NeuroStar TMS therapy is <strong>less than 0.1% per course of treatment (1 in 30,000 sessions)</strong>.
                    </p>
                    <p>
                        To put this into clinical perspective, the seizure risk associated with NeuroStar TMS is comparable to or lower than the baseline seizure risk associated with common oral antidepressant medications such as Bupropion (Wellbutrin) or tricyclic antidepressants.
                    </p>
                    <p>
                        At Tranquil Minds Mental Health, we minimize seizure risk through strict clinical protocols:
                    </p>
                    <ul class="list-disc ml-6 space-y-2 mb-6">
                        <li><strong>Motor Threshold Calibration:</strong> We measure your individual Motor Threshold (MT) prior to treatment to deliver the precise minimal energy required.</li>
                        <li><strong>Medical Screening:</strong> We screen thoroughly for pre-existing seizure disorders, epilepsy, traumatic brain injuries (TBI), or concurrent medications that lower seizure threshold.</li>
                    </ul>

                    <h3 class="text-2xl text-primary mt-8 mb-4 font-semibold">NeuroStar TMS vs. ECT (Electroconvulsive Therapy): Debunking the Myth</h3>
