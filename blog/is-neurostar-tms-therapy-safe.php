                        Patients often confuse Transcranial Magnetic Stimulation (TMS) with Electroconvulsive Therapy (ECT). It is critical to emphasize that <strong>TMS is NOT ECT</strong>. They are fundamentally different procedures in technology, administration, side effects, and patient experience.
                    </p>

