                            <p class="text-sm text-gray-600 leading-relaxed">
                                One-on-one sessions, usually billed as 30, 45 (CPT 90834), or 60-minute (CPT 90837) psychotherapy visits. This is the most commonly covered form of talk therapy.
                            </p>
                        </div>
                        <div class="bg-[#FAFAFF] border border-primary/10 p-6 rounded-2xl shadow-sm">
                            <h4 class="text-xl font-bold text-primary mb-2">Family &amp; Couples Therapy</h4>
                            <p class="text-sm text-gray-600 leading-relaxed">
                                Often covered when family involvement supports the treatment of a diagnosed patient. Couples counseling for relationship issues alone may not be covered.
                            </p>
                        </div>
                        <div class="bg-[#FAFAFF] border border-primary/10 p-6 rounded-2xl shadow-sm">
                            <h4 class="text-xl font-bold text-primary mb-2">Group Therapy</h4>
                            <p class="text-sm text-gray-600 leading-relaxed">
                                Clinician-led groups for depression, anxiety, grief, or skills training are generally covered and often cost less per session.
                            </p>
                        </div>
                        <div class="bg-[#FAFAFF] border border-primary/10 p-6 rounded-2xl shadow-sm">
                            <h4 class="text-xl font-bold text-primary mb-2">Telehealth Therapy</h4>
                            <p class="text-sm text-gray-600 leading-relaxed">
                                Secure video sessions are covered by most plans, often at the same cost as in-person visits. Minnesota has strong telehealth coverage rules.
                            </p>
                        </div>
                    </div>

                    <h3 class="text-2xl text-primary mt-8 mb-4 font-semibold">Common Therapy Approaches Insurance Pays For</h3>
                    <ul class="list-disc pl-5 mb-6 space-y-2">
                        <li><strong>Cognitive Behavioral Therapy (CBT):</strong> A first-line approach for depression and anxiety.</li>
                        <li><strong>Dialectical Behavior Therapy (DBT):</strong> Builds emotion regulation and distress tolerance skills.</li>
                        <li><strong>Trauma-focused therapy and EMDR:</strong> Commonly used for PTSD and trauma.</li>
                        <li><strong>Exposure and Response Prevention (ERP):</strong> The leading therapy for OCD.</li>
                        <li><strong>Acceptance and Commitment Therapy (ACT):</strong> Builds psychological flexibility and values-based action.</li>
                    </ul>

                    <h3 class="text-2xl text-primary mt-8 mb-4 font-semibold">What Insurance Often Does Not Cover</h3>
                    <p>
                        Plans generally do not pay for services that are not tied to a diagnosed condition, such as life coaching, career counseling, or general personal growth sessions. Missed-appointment fees, some court-ordered evaluations, and sessions with out-of-network providers on HMO plans are also commonly excluded.
                    </p>

