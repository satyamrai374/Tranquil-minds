                    <!-- Section 7: Social Security Benefits -->
                    <h2 id="social-security-benefits" class="text-3xl text-primary mt-12 mb-5" style="font-family: 'Bauhaus Soft', cursive;">Qualifying for Social Security Disability (SSDI &amp; SSI)</h2>
                    <p>
                        When severe OCD prevents gainful employment, you can qualify for monthly benefits under SSDI or SSI. The SSA evaluates claims under <strong>Blue Book Listing 12.06</strong> requiring:
                    </p>
                    <ul class="list-disc pl-5 mb-6 space-y-2">
                        <li><strong>Paragraph A:</strong> Medical records documenting involuntary, time-consuming obsessions or compulsions.</li>
                        <li><strong>Paragraph B:</strong> Extreme limitation in one, or marked limitation in two, functional areas: understanding/memory, social interaction, concentration/pace, or self-management.</li>
                        <li><strong>Paragraph C:</strong> Or a medically documented history of persistent OCD over at least two years with ongoing treatment and marginal adjustment.</li>
                    </ul>
                    <p>
                        Claims not meeting Listing 12.06 are evaluated via a <strong>Residual Functional Capacity (RFC)</strong> assessment. If records show compulsions keep you off-task &gt;15% of the workday or cause &gt;2 monthly absences, benefits can be awarded. Also review our guide on <a href="does-medicaid-cover-psychotherapy.php" class="text-accent underline hover:text-accent-light">Medicaid coverage for mental healthcare</a>.
                    </p>

